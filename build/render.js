// Turns composed spreads into the page. Grid placement travels on the element
// as custom properties so the stylesheet stays readable and the design can be
// edited without running the build.
import { INDEXABLE, SITE_TITLE } from './config.js';

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// Are.na resizes to fit inside a square box, so a portrait image's real width
// is the box times its ratio. Never claim more pixels than the original has.
const widthAt = (box, block) => Math.min(
  Math.round(box * Math.min(1, block.image.ratio || 1)),
  block.image.width || box
);

const FILENAME = /\.(jpe?g|png|gif|webp|avif|tiff?)$/i;
const SCREENSHOT = /^(screen ?shot|screenshot|img[_-]?\d|image[_-]?\d|untitled|unnamed|photo[_-]?\d|pasted)/i;
const worthShowing = (t) => t && !FILENAME.test(t) && !SCREENSHOT.test(t.trim());

// Placement for all three grids — twelve columns, eight, four — is decided in
// spreads.js and travels on the element. The stylesheet only chooses which set
// of custom properties is in force at a given width.
function placement(slot) {
  return [
    `--col:${slot.col}`, `--span:${slot.span}`, `--row:${slot.row}`,
    `--mcol:${slot.mcol}`, `--mspan:${slot.mspan}`, `--mrow:${slot.mrow}`,
    `--scol:${slot.scol}`, `--sspan:${slot.sspan}`, `--srow:${slot.srow}`,
  ].join(';');
}

function sizes(slot) {
  const pct = (span, cols) => Math.round(span / cols * 100);
  return `(min-width: 900px) ${pct(slot.span, 12)}vw, ` +
         `(min-width: 560px) ${pct(slot.mspan, 8)}vw, ${pct(slot.sspan, 4)}vw`;
}

function imageSlot(slot) {
  const b = slot.block;
  const files = b.files || [];
  const byName = Object.fromEntries(files.map(f => [f.split('-').pop().split('.')[0], f]));
  const medium = byName.medium || files[0];
  const large = byName.large || medium;

  const srcset = [
    medium && `images/${medium} ${widthAt(1200, b)}w`,
    large && large !== medium && `images/${large} ${widthAt(1800, b)}w`,
  ].filter(Boolean).join(', ');

  const label = worthShowing(b.title) ? b.title : '';
  const ratio = (b.image.ratio || 1).toFixed(4);

  const picture = `<img src="images/${esc(large)}" srcset="${esc(srcset)}" sizes="${sizes(slot)}"` +
    (b.image.width ? ` width="${b.image.width}" height="${b.image.height}"` : '') +
    ` alt="${esc(b.alt)}" loading="lazy" decoding="async">`;

  // Blocks that came from somewhere link back to it. Are.na block URLs are not
  // used: the channel is private, so they would 404 for everyone but Betty.
  const frame = b.source
    ? `<a class="frame" style="--ratio:${ratio}" href="${esc(b.source)}" target="_blank" rel="noreferrer">${picture}</a>`
    : `<div class="frame" style="--ratio:${ratio}">${picture}</div>`;

  return `      <figure class="slot image" data-align="${slot.align || 'start'}" style="${placement(slot)}">
        ${frame}${label ? `\n        <figcaption class="label">${esc(label)}</figcaption>` : ''}
      </figure>`;
}

function textSlot(slot) {
  const paragraphs = slot.block.text
    .split(/\n{2,}/)
    .map(p => `<p>${esc(p.trim()).replace(/\n/g, '<br>')}</p>`)
    .join('\n          ');
  return `      <div class="slot text text-${slot.size || 'medium'}" style="${placement(slot)}">
          ${paragraphs}
      </div>`;
}

export function render(spreads, meta) {
  const bands = spreads.map((spread, i) => {
    const slots = spread.slots
      .map(s => (s.kind === 'text' ? textSlot(s) : imageSlot(s)))
      .join('\n');
    return `    <section class="spread spread--${spread.name}" data-rhythm="${i % 4}">\n${slots}\n    </section>`;
  }).join('\n\n');

  const counts = spreads.flatMap(s => s.slots).reduce((acc, s) => (acc[s.kind]++, acc), { image: 0, text: 0 });

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${esc(SITE_TITLE)}</title>${INDEXABLE ? '' : '\n  <meta name="robots" content="noindex, nofollow">'}
  <link rel="stylesheet" href="styles.css">
  <!-- Generated by build/build.js from the Are.na channel ${esc(meta.channel.slug)}.
       ${counts.image} images, ${counts.text} texts, ${spreads.length} spreads.
       Last collected ${esc(meta.fetched_at)}. Edit styles.css, not this file. -->
</head>
<body>
  <main>
${bands}
  </main>
</body>
</html>
`;
}
